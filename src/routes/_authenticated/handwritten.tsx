/** Downscale to a JPEG blob + data URL (max 1600px) so uploads and OCR stay small. */
async function compressImage(file: File): Promise<{ dataUrl: string; blob: Blob }> {
  const url = URL.createObjectURL(file);
  try {
    const img = await new Promise<HTMLImageElement>((resolve, reject) => {
      const el = new Image();
      el.onload = () => resolve(el);
      el.onerror = () => reject(new Error("image load failed"));
      el.src = url;
    });
    const MAX = 1600;
    const scale = Math.min(1, MAX / Math.max(img.width, img.height));
    const w = Math.max(1, Math.round(img.width * scale));
    const h = Math.max(1, Math.round(img.height * scale));
    const canvas = document.createElement("canvas");
    canvas.width = w;
    canvas.height = h;
    const ctx = canvas.getContext("2d");
    if (!ctx) throw new Error("canvas unavailable");
    ctx.fillStyle = "#ffffff";
    ctx.fillRect(0, 0, w, h);
    ctx.drawImage(img, 0, 0, w, h);
    const blob = await new Promise<Blob | null>((resolve) =>
      canvas.toBlob(resolve, "image/jpeg", 0.85),
    );
    if (!blob) throw new Error("canvas toBlob failed");
    const dataUrl = await new Promise<string>((resolve, reject) => {
      const reader = new FileReader();
      reader.onload = () => resolve(String(reader.result));
      reader.onerror = () => reject(new Error("read failed"));
      reader.readAsDataURL(blob);
    });
    return { dataUrl, blob };
  } finally {
    URL.revokeObjectURL(url);
  }
}

function ocrErrorKey(code: string): string {
  if (code === "VISION_NOT_CONFIGURED") return "hwOcrNotConfigured";
  if (code === "VISION_UNSUPPORTED") return "hwVisionUnsupported";
  if (code === "UNAUTHORIZED") return "aiGradeUnauthorized";
  return "hwOcrFailed";
}

